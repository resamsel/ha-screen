"""Montserrat with Latin-1 (umlauts, ß, µ, ³ ...) as LVGL 8 fonts, for the text sizes that
show HA names, titles and units. LVGL's built-in fonts are ASCII only. Glyphs missing here
(the LV_SYMBOL_* icons) fall back to the built-in font of the same size.

Usage (repo root): python3 tools/make_fonts.py
"""
import re
from PIL import Image, ImageDraw, ImageFont

TTF = "managed_components/lvgl__lvgl/scripts/built_in_font/Montserrat-Medium.ttf"
SIZES = [12, 14, 16, 22]
RANGES = [(0x20, 0x7F), (0xA0, 0xFF)]   # inclusive


def glyph(font, ascent, ch):
    x0, y0, x1, y1 = font.getbbox(ch)
    w, h = max(x1 - x0, 0), max(y1 - y0, 0)
    adv = round(font.getlength(ch) * 16)
    px = []
    if w and h:
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
        px = [v >> 4 for v in img.getdata()]           # 4 bpp
    return dict(adv=adv, w=w, h=h, ox=x0, oy=ascent - y1, px=px)


def pack4(px):
    """4 bpp, rows packed back to back (LVGL plain bitmap format)"""
    out = []
    for i in range(0, len(px), 2):
        hi = px[i]
        lo = px[i + 1] if i + 1 < len(px) else 0
        out.append(hi << 4 | lo)
    return out


def builtin_metrics(size):
    """line_height/base_line of LVGL's built-in font, so layouts don't move"""
    src = open(f"managed_components/lvgl__lvgl/src/font/lv_font_montserrat_{size}.c").read()
    lh = int(re.search(r"\.line_height = (\d+)", src).group(1))
    bl = int(re.search(r"\.base_line = (\d+)", src).group(1))
    return lh, bl


def make(size):
    name = f"lv_font_latin_{size}"
    font = ImageFont.truetype(TTF, size)
    ascent, _ = font.getmetrics()
    line_height, base_line = builtin_metrics(size)
    bitmap, dscs = [], ["{.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0}"]
    for a, b in RANGES:
        for cp in range(a, b + 1):
            g = glyph(font, ascent, chr(cp))
            dscs.append(f"{{.bitmap_index = {len(bitmap)}, .adv_w = {g['adv']}, .box_w = {g['w']}, "
                        f".box_h = {g['h']}, .ofs_x = {g['ox']}, .ofs_y = {g['oy']}}}")
            bitmap += pack4(g["px"])
    cmaps, gid = [], 1
    for a, b in RANGES:
        n = b - a + 1
        cmaps.append(f"{{.range_start = {a}, .range_length = {n}, .glyph_id_start = {gid}, "
                     ".unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, "
                     ".type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}")
        gid += n
    with open(f"main/fonts/{name}.c", "w") as f:
        f.write(f"/* Generated by tools/make_fonts.py: Montserrat Medium {size} px, 4 bpp, "
                "U+0020-007F U+00A0-00FF */\n#include \"lvgl.h\"\n\n")
        f.write("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {\n")
        for i in range(0, len(bitmap), 24):
            f.write("    " + ",".join(f"0x{v:02x}" for v in bitmap[i:i + 24]) + ",\n")
        f.write("};\n\nstatic const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {\n")
        f.write(",\n".join("    " + d for d in dscs) + "\n};\n\n")
        f.write("static const lv_font_fmt_txt_cmap_t cmaps[] = {\n")
        f.write(",\n".join("    " + c for c in cmaps) + "\n};\n\n")
        f.write("static lv_font_fmt_txt_glyph_cache_t cache;\n\n")
        f.write("static const lv_font_fmt_txt_dsc_t font_dsc = {\n"
                "    .glyph_bitmap = glyph_bitmap,\n    .glyph_dsc = glyph_dsc,\n    .cmaps = cmaps,\n"
                "    .kern_dsc = NULL,\n    .kern_scale = 0,\n"
                f"    .cmap_num = {len(cmaps)},\n    .bpp = 4,\n    .kern_classes = 0,\n"
                "    .bitmap_format = 0,\n    .cache = &cache,\n};\n\n")
        f.write(f"extern const lv_font_t lv_font_montserrat_{size};\n\n")
        f.write(f"const lv_font_t {name} = {{\n"
                "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,\n"
                "    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,\n"
                f"    .line_height = {line_height},\n    .base_line = {base_line},\n"
                "    .subpx = LV_FONT_SUBPX_NONE,\n"
                f"    .underline_position = {-max(1, size // 10)},\n    .underline_thickness = {max(1, size // 14)},\n"
                f"    .dsc = &font_dsc,\n    .fallback = &lv_font_montserrat_{size},\n}};\n")
    print(name, "line_height", line_height, "base_line", base_line, "bytes", len(bitmap))


for s in SIZES:
    make(s)
