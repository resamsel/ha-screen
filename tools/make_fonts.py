# no glyph, no width: variation selectors, zero-width joiner, skin tones (LVGL would draw a box)
EMOJI_INVISIBLE = [0x200D, 0xFE0E, 0xFE0F] + list(range(0x1F3FB, 0x1F400))


def make_emoji(ttf, size=16, px=14):
    from PIL import Image as _I
    name = f"lv_font_emoji_{size}"
    font = ImageFont.truetype(ttf, px)
    notdef = bytes(font.getmask(chr(0x10FFFD)))
    line_height, base_line = builtin_metrics(size)
    ascent, _ = font.getmetrics()
    cps = sorted({ord(c) for c in EMOJI} | set(EMOJI_INVISIBLE))
    bitmap, dscs, kept, missing = [], ["{.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0}"], [], []
    for cp in cps:
        if cp in EMOJI_INVISIBLE:
            g = dict(adv=0, w=0, h=0, ox=0, oy=0, px=[])
        else:
            if bytes(font.getmask(chr(cp))) == notdef:
                missing.append(chr(cp))
                continue
            g = glyph(font, ascent, chr(cp))
            g["oy"] -= 2                       # sit like a capital letter of the 16 px text
        kept.append(cp)
        dscs.append(f"{{.bitmap_index = {len(bitmap)}, .adv_w = {g['adv']}, .box_w = {g['w']}, "
                    f".box_h = {g['h']}, .ofs_x = {g['ox']}, .ofs_y = {g['oy']}}}")
        bitmap += pack4(g["px"])
    # sparse cmaps: one per block of up to 65535 code points after its start
    groups, cur = [], []
    for cp in kept:
        if cur and cp - cur[0] > 0xFFFF:
            groups.append(cur); cur = []
        cur.append(cp)
    if cur: groups.append(cur)
    out = [f"/* Generated by tools/make_fonts.py --emoji: Noto Emoji {px} px for {size} px text, 4 bpp,\n"
           f" * {len(kept)} glyphs. Font: SIL Open Font License 1.1, see OFL-NotoEmoji.txt */\n#include \"lvgl.h\"\n\n",
           "static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {\n"]
    for i in range(0, len(bitmap), 24):
        out.append("    " + ",".join(f"0x{v:02x}" for v in bitmap[i:i + 24]) + ",\n")
    out.append("};\n\nstatic const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {\n" + ",\n".join("    " + d for d in dscs) + "\n};\n\n")
    cmaps, gid = [], 1
    for k, g in enumerate(groups):
        out.append(f"static const uint16_t unicode_list_{k}[] = {{" + ", ".join(f"0x{cp - g[0]:x}" for cp in g) + "};\n")
        cmaps.append(f"{{.range_start = {g[0]}, .range_length = {g[-1] - g[0] + 1}, .glyph_id_start = {gid}, "
                     f".unicode_list = unicode_list_{k}, .glyph_id_ofs_list = NULL, .list_length = {len(g)}, "
                     ".type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}")
        gid += len(g)
    out.append("\nstatic const lv_font_fmt_txt_cmap_t cmaps[] = {\n" + ",\n".join("    " + c for c in cmaps) + "\n};\n\n")
    out.append("static lv_font_fmt_txt_glyph_cache_t cache;\n\n"
               "static const lv_font_fmt_txt_dsc_t font_dsc = {\n"
               "    .glyph_bitmap = glyph_bitmap,\n    .glyph_dsc = glyph_dsc,\n    .cmaps = cmaps,\n"
               "    .kern_dsc = NULL,\n    .kern_scale = 0,\n"
               f"    .cmap_num = {len(cmaps)},\n    .bpp = 4,\n    .kern_classes = 0,\n"
               "    .bitmap_format = 0,\n    .cache = &cache,\n};\n\n"
               f"extern const lv_font_t lv_font_latin_{size};\n\n"
               f"/* the emoji, then the 16 px text font for everything else */\nconst lv_font_t {name} = {{\n"
               "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,\n"
               "    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,\n"
               f"    .line_height = {line_height},\n    .base_line = {base_line},\n"
               "    .subpx = LV_FONT_SUBPX_NONE,\n"
               f"    .underline_position = {-max(1, size // 10)},\n    .underline_thickness = {max(1, size // 14)},\n"
               f"    .dsc = &font_dsc,\n    .fallback = &lv_font_latin_{size},\n}};\n")
    open(f"main/fonts/{name}.c", "w").write("".join(out))
    print(name, "glyphs", len(kept), "bytes", len(bitmap), "missing", "".join(missing) or "none")


if __name__ == "__main__":
    main()
