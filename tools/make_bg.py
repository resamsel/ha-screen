"""Convert a theme background to an LVGL 8 RGB565 (byte-swapped) C image.

The image is a 320x320 centre crop so it covers the screen in both orientations
(172x320 portrait, 320x172 landscape); LVGL draws it centred.

Usage: python3 tools/make_bg.py tools/bg_dark_src.png main/bg_dark.c bg_dark
       python3 tools/make_bg.py tools/bg_light_src.png main/bg_light.c bg_light
"""
import sys
from PIL import Image

SIZE = 320
NAME = sys.argv[3]
BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]

img = Image.open(sys.argv[1]).convert("RGB")
w, h = img.size
s = min(w, h)
img = img.crop(((w - s) // 2, (h - s) // 2, (w + s) // 2, (h + s) // 2))
img = img.resize((SIZE, SIZE), Image.LANCZOS)

px = []
for i, (r, g, b) in enumerate(img.getdata()):
    # ordered dither so the smooth gradients don't band in RGB565
    t = BAYER[(i // SIZE) % 4][i % SIZE % 4] / 16 - 0.5
    r = min(255, max(0, int(r + t * 8)))
    g = min(255, max(0, int(g + t * 4)))
    b = min(255, max(0, int(b + t * 8)))
    v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    px += [(v >> 8) & 0xFF, v & 0xFF]  # swapped RGB565 (LV_COLOR_16_SWAP=1)

with open(sys.argv[2], "w") as f:
    f.write(f"/* Generated by tools/make_bg.py from {sys.argv[1]} */\n")
    f.write('#include "lvgl.h"\n\n')
    f.write(f"static const uint8_t {NAME}_map[] = {{\n")
    for i in range(0, len(px), 32):
        f.write("  " + ",".join(f"0x{v:02x}" for v in px[i:i + 32]) + ",\n")
    f.write("};\n\n")
    f.write(f"const lv_img_dsc_t {NAME} = {{\n")
    f.write("  .header.cf = LV_IMG_CF_TRUE_COLOR,\n  .header.always_zero = 0,\n")
    f.write(f"  .header.w = {SIZE},\n  .header.h = {SIZE},\n")
    f.write(f"  .data_size = {len(px)},\n  .data = {NAME}_map,\n}};\n")
